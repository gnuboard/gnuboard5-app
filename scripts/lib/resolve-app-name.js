/**
 * 앱 표시 이름 빌드 시 동기화 — 순수 로직 (jest 로 테스트, `scripts/sync-app-name.mjs` 가 호출).
 *
 * 그누보드 `$config['cf_title']` 은 `GET {API}/settings → data.cf_title` 로 노출된다.
 * 네이티브 라벨/스토어 표시명은 동적일 수 없으므로 빌드 전에 이 값을 `EXPO_PUBLIC_APP_NAME` 에 고정한다(ARCH §3.4 (b)).
 */
'use strict';

const ENV_KEY = 'EXPO_PUBLIC_APP_NAME';
const MAX_NAME_LENGTH = 120;
const FETCH_TIMEOUT_MS = 15000;

class AppNameSyncError extends Error {
  /** @param {string} message @param {'network'|'http'|'envelope'|'empty'} code */
  constructor(message, code) {
    super(message);
    this.name = 'AppNameSyncError';
    this.code = code;
  }
}

/**
 * `/settings` 응답 JSON 에서 표시 이름을 뽑는다. 비어 있거나 형식이 다르면 throw — 빌드를 중단시켜야 하므로 폴백하지 않는다.
 * @param {unknown} json
 * @returns {string}
 */
function resolveAppNameFromSettings(json) {
  if (!json || typeof json !== 'object' || Array.isArray(json)) {
    throw new AppNameSyncError('settings response is not an object', 'envelope');
  }
  const envelope = /** @type {{ success?: unknown, data?: unknown }} */ (json);
  if (envelope.success !== true || !envelope.data || typeof envelope.data !== 'object') {
    throw new AppNameSyncError('settings envelope is not {success:true, data:{...}}', 'envelope');
  }
  const title = /** @type {{ cf_title?: unknown }} */ (envelope.data).cf_title;
  const trimmed = typeof title === 'string' ? title.trim().replace(/\s+/g, ' ') : '';
  if (!trimmed) throw new AppNameSyncError('cf_title is empty — set 사이트 제목 in /adm/config_form.php', 'empty');
  return trimmed.slice(0, MAX_NAME_LENGTH);
}

/**
 * @param {string} apiBase e.g. https://gnuboard.example.com/api/v1
 * @param {typeof fetch} [fetchImpl]
 * @returns {Promise<string>}
 */
async function fetchAppName(apiBase, fetchImpl = fetch) {
  const url = `${apiBase.replace(/\/+$/, '')}/settings`;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  let response;
  try {
    response = await fetchImpl(url, { headers: { Accept: 'application/json' }, signal: controller.signal });
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new AppNameSyncError(`cannot reach ${url}: ${reason}`, 'network');
  } finally {
    clearTimeout(timer);
  }
  if (!response.ok) throw new AppNameSyncError(`${url} responded HTTP ${response.status}`, 'http');
  let json;
  try {
    json = await response.json();
  } catch {
    throw new AppNameSyncError(`${url} did not return JSON`, 'envelope');
  }
  return resolveAppNameFromSettings(json);
}

/**
 * dotenv 파일 내용. 따옴표로 감싸 공백·`#` 을 보호한다.
 * @param {string} name
 */
function renderEnvFile(name) {
  const escaped = name.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return `# generated by scripts/sync-app-name.mjs — do not edit, do not commit\n${ENV_KEY}="${escaped}"\n`;
}

module.exports = {
  ENV_KEY,
  AppNameSyncError,
  resolveAppNameFromSettings,
  fetchAppName,
  renderEnvFile,
};
